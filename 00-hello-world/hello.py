#!/usr/bin/env python3
"""
============================================================================
 Python 语言圣经
 卷一 · 语言
 第 0 章 · Hello, World!

 “起初，只有源代码。”
============================================================================

 本文件既是程序，也是课文。

 它只用了五种语法：

     1. 注释
     2. 函数定义
     3. 函数调用表达式
     4. 字符串字面量
     5. if 语句与模块级名字 __name__

 运行：
     python3 hello.py

============================================================================
"""

# 注释：从 # 到本行末尾，解释器会忽略它。
# Python 没有 C 那样的块注释；多行说明通常用三引号字符串（文档字符串）。


def main() -> None:
    """
    函数定义：

        def main() -> None:

    def       声明一个函数
    main      函数名
    ()        参数列表：这里没有参数
    -> None   返回类型注解：这个函数返回 None
    :         函数头结束，下面是缩进的函数体

    Python 用缩进划分代码块，不用花括号。
    函数体必须比 def 多缩进一级；本书统一用 4 个空格。
    """

    # 函数调用表达式：
    #
    #     print("Hello, World!")
    #
    # print     内置函数
    # (...)     参数列表
    # "..."     字符串字面量
    #
    # print 默认在末尾输出一个换行符，并返回 None。
    # 它不是语句关键字，而是一个普通函数；这是 Python 3 与 Python 2 的重要区别。
    print("Hello, World!")


# 模块级名字 __name__ 由解释器设置：
#
#   - 直接运行这个文件时，__name__ 等于 "__main__"；
#   - 被别的模块 import 时，__name__ 等于模块名。
#
# 这个 if 让“导入时只提供函数、直接运行时才执行 main”成为可能。
# 第 8 章会详细讲模块和导入。
if __name__ == "__main__":
    main()
